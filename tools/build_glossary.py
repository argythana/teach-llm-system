#!/usr/bin/env python
"""Generate ``glossary.md``, the course's terms, from the notebooks' definition bullets.

Every definition bullet (``- [A/An/The] **term** is/are ...``, rules in CLAUDE.md) becomes
one entry, grouped by lecture in teaching order, with a link to the notebook and section
that defines it. Exercises define nothing, so they are left out. Do not edit
``glossary.md`` by hand: edit the definition in its notebook, then rerun this script.

Usage:
    uv run python tools/build_glossary.py           # write glossary.md
    uv run python tools/build_glossary.py --check   # fail if stale or a term is defined twice
"""

from __future__ import annotations

import argparse
import sys
from importlib.metadata import entry_points

import mdformat
from notebook_prose import REPO, Definition, course_notebooks, definitions, normalize

GLOSSARY = REPO / "glossary.md"

INTRO = """\
# Course terms

Every term the notebooks define, in the order they teach them, with a link to the
notebook and section that defines it. Read a notebook first; come back here to revise.

This file is generated by `tools/build_glossary.py` from the definition bullets of the
notebooks: change a definition in its notebook, then rerun the script.
"""


def _lecture_title(lecture: int) -> str:
    goals = next(REPO.glob(f"lecture_{lecture:02d}_*/reading_material/goals_*.md"))
    return goals.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()


def _entry(d: Definition) -> str:
    link = d.notebook.path.relative_to(REPO).as_posix()
    where = d.section if d.section.startswith("§") else f"({d.section})"
    return f"- {d.text} ([`{d.notebook.short}` {where}]({link}))"


def render(defs: list[Definition]) -> str:
    parts = [INTRO]
    for lecture in sorted({d.notebook.lecture for d in defs}):
        in_lecture = [d for d in defs if d.notebook.lecture == lecture]
        mandatory = [d for d in in_lecture if d.notebook.mandatory]
        optional = [d for d in in_lecture if not d.notebook.mandatory]
        parts.append(f"## {_lecture_title(lecture)}\n")
        if mandatory:
            parts.append("\n".join(_entry(d) for d in mandatory) + "\n")
        if optional:
            parts.append("### Optional / career-track notebooks\n")
            parts.append("\n".join(_entry(d) for d in optional) + "\n")
    extensions = {e.name for e in entry_points(group="mdformat.parser_extension")}
    return mdformat.text("\n".join(parts), options={"wrap": 88}, extensions=extensions)


def duplicates(defs: list[Definition]) -> list[str]:
    seen: dict[str, Definition] = {}
    found = []
    for d in defs:
        key = normalize(d.term)
        if key in seen:
            first = seen[key]
            found.append(
                f"'{d.term}' is defined in {first.notebook.short} cell {first.cell} "
                f"and again in {d.notebook.short} cell {d.cell}"
            )
        else:
            seen[key] = d
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if glossary.md is stale")
    args = ap.parse_args()
    notebooks = [nb for nb in course_notebooks() if not nb.is_exercises]
    defs = definitions(notebooks)
    text = render(defs)
    problems = duplicates(defs)
    for p in problems:
        print(f"defined twice: {p}", file=sys.stderr)
    if args.check:
        current = GLOSSARY.read_text(encoding="utf-8") if GLOSSARY.exists() else ""
        if current != text:
            print(
                "glossary.md is stale: run `uv run python tools/build_glossary.py`",
                file=sys.stderr,
            )
            return 1
        return 1 if problems else 0
    GLOSSARY.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {GLOSSARY.relative_to(REPO)}: {len(defs)} terms")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
